export function glyph(ch) { return G[ch] || G[ch.toUpperCase()] || G['?']; }
export function textWidth(str) { let w = 0; for (const ch of str) w += glyph(ch)[0].length + 1; return Math.max(0, w - 1); }

// Draw text with outline + drop shadow + vertical gradient fill. px = device pixels per font pixel.
// reveal: number of characters visible (typewriter)
export function drawText(ctx, str, x, y, px, opts = {}) {
  const fill = opts.fill || ['#fff6d6', '#f2cf73', '#d99a3a'];
  const outline = opts.outline || '#1a0f08', shadow = opts.shadow ?? 'rgba(4,8,20,0.55)';
  const reveal = opts.reveal ?? Infinity;
  const align = opts.align || 'center';
  const W = textWidth(str) * px;
  let ox = align === 'center' ? Math.round(x - W / 2) : align === 'right' ? Math.round(x - W) : Math.round(x);
  const oy = Math.round(y);
  ctx.globalAlpha = opts.alpha ?? 1;
  // collect pixels
  const pts = []; let cx = 0, n = 0;
  for (const ch of str) {
    if (n++ >= reveal) break;
    const g = glyph(ch);
    for (let r = 0; r < 7; r++) for (let c = 0; c < g[r].length; c++) if (g[r][c] === '#') pts.push([cx + c, r]);
    cx += g[0].length + 1;
  }
  const P = (gx, gy, dx, dy) => ctx.fillRect(ox + (gx + dx) * px, oy + (gy + dy) * px, px, px);
  if (shadow) { ctx.fillStyle = shadow; for (const [gx, gy] of pts) P(gx, gy, 1, 2); }
  if (outline) {
    ctx.fillStyle = outline;
    for (const [gx, gy] of pts) { P(gx, gy, -1, 0); P(gx, gy, 1, 0); P(gx, gy, 0, -1); P(gx, gy, 0, 1); P(gx, gy, 1, 1); }
  }
  for (const [gx, gy] of pts) { ctx.fillStyle = gy < 2 ? fill[0] : gy < 5 ? fill[1] : fill[2]; P(gx, gy, 0, 0); }
  ctx.globalAlpha = 1;
  return W;
}
// word-wrap to a max width in font pixels
export function wrap(str, maxW) {
  const words = str.split(' '); const lines = []; let cur = '';
  for (const w of words) {
    const t = cur ? cur + ' ' + w : w;
    if (textWidth(t) > maxW && cur) { lines.push(cur); cur = w; } else cur = t;
  }
  if (cur) lines.push(cur);
  return lines;
}
